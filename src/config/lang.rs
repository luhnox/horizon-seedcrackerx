/// The table of a language by its code (`en_us`), English where the mod has none for it.
fn table(language: &str) -> &'static [(&'static str, &'static str)] {
    match language {
        "hi_in" => &HI_IN,
        "ru_ru" => &RU_RU,
        "tr_tr" => &TR_TR,
        "zh_cn" => &ZH_CN,
        _ => &EN_US,
    }
}

/// `Language.getInstance().getOrDefault(key)`.
pub fn translate(language: &str, key: &str) -> String {
    for t in [table(language), &EN_US[..]] {
        if let Some((_, v)) = t.iter().find(|(k, _)| *k == key) {
            return (*v).to_owned();
        }
    }
    key.to_owned()
}

/// `String.formatted(args)` for the `%s` and `%d` of a message.
pub fn format(template: &str, args: &[String]) -> String {
    let mut out = String::new();
    let mut next = args.iter();
    let mut chars = template.chars().peekable();
    while let Some(c) = chars.next() {
        if c == '%' {
            match chars.peek() {
                Some('s') | Some('d') => {
                    chars.next();
                    out.push_str(next.next().map_or("null", String::as_str));
                    continue;
                }
                Some('%') => {
                    chars.next();
                    out.push('%');
                    continue;
                }
                _ => {}
            }
        }
        out.push(c);
    }
    out
}
